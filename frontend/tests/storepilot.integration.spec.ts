test('real API: retry recovers when a ticket committed but its response was lost', async ({ page }) => {
  await signIn(page)
  await page.getByRole('button', { name: 'Copilot', exact: true }).click()
  await page.getByLabel('Message', { exact: true }).fill(
    'One register card reader is down since 10am, error E42. Other registers work.'
  )
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Generate ticket', exact: true })).toBeVisible()
  const keys: string[] = []
  let first = true
  await page.route('**/api/tickets', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    keys.push(route.request().headers()['idempotency-key'])
    if (!first) return route.continue()
    first = false
    const committed = await route.fetch()
    expect(committed.status()).toBe(201)
    await route.fulfill({
      status: 503, contentType: 'application/json',
      body: JSON.stringify({ code: 'unavailable', message: 'Reply lost after commit' }),
    })
  })
  await page.getByRole('button', { name: 'Generate ticket', exact: true }).click()
  await page.getByRole('button', { name: 'Retry ticket save', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Ticket created: TKT-' })).toBeVisible()
  expect(keys).toHaveLength(2)
  expect(keys[0]).toBe(keys[1])
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
})

