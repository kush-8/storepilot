test('real API: default dashboard includes existing open cases and persists new tickets after reload', async ({ page }) => {
  const dashboardResponse = page.waitForResponse(response =>
    new URL(response.url()).pathname === '/api/dashboard'
  )
  await signIn(page)
  await expect(page.getByLabel('Data source')).toHaveValue('open')
  await expect(page.getByLabel('Time range')).toHaveValue('all')
  const before = await (await dashboardResponse).json()
  expect(before.metrics.open).toBeGreaterThan(0)
  expect(before.context.filters.data_mode).toBe('combined')
  expect(before.context.filters.status).toBe('Open')
  await expect(page.getByRole('table').first().getByRole('cell', { name: 'Closed', exact: true })).toHaveCount(0)
  await expect(page.getByRole('table').first().getByRole('row').nth(1)).toBeVisible()

  await page.getByRole('button', { name: 'Copilot', exact: true }).click()
  await page.getByLabel('Message', { exact: true }).fill(
    'One register card reader is down since 10am, error E42. Other registers work.'
  )
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByRole('button', { name: 'Generate ticket', exact: true }).click()
  const receipt = page.getByRole('status').filter({ hasText: 'Ticket created: TKT-' })
  await expect(receipt).toBeVisible()
  const identifier = (await receipt.innerText()).replace('Ticket created: ', '').trim()
  const reloadedDashboard = page.waitForResponse(response =>
    new URL(response.url()).pathname === '/api/dashboard'
  )
  await page.reload()
  const after = await (await reloadedDashboard).json()
  expect(after.metrics.total).toBe(before.metrics.total + 1)
  await expect(page.getByRole('row').filter({ hasText: identifier })).toBeVisible()
  await page.getByRole('button', { name: 'Analytics/Query', exact: true }).click()
  await page.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Open')
  await page.getByLabel('Analytics question').fill('Count tickets by store')
  await page.getByRole('button', { name: 'Ask', exact: true }).click()
  await expect(page.getByText(`${after.metrics.total} authorized tickets match; grouped by affected_store_id.`)).toBeVisible()
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click()
  await page.getByRole('button', { name: identifier, exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('combobox', { name: 'Status', exact: true }).selectOption('Closed')
  await dialog.getByRole('button', { name: 'Update status', exact: true }).click()
  await expect(dialog.getByText(/Closed · ST008/)).toBeVisible()
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: identifier })).toHaveCount(0)
  await page.getByLabel('Data source').selectOption('combined')
  const closedRow = page.getByRole('row').filter({ hasText: identifier })
  await expect(closedRow.getByRole('cell', { name: 'Closed', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
})

