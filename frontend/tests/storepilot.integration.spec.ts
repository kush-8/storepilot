test('real API: broad analytics renders SQL results as readable text', async ({ page }) => {
  await signIn(page)
  await page.getByRole('button', { name: 'Analytics/Query', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Ask StorePilot' })).toBeVisible()
  await page.getByLabel('Analytics question').fill('What is the most frequent issue in store ST004?')
  const response = page.waitForResponse(res => res.url().endsWith('/api/dashboard/analytics'))
  await page.getByRole('button', { name: 'Ask', exact: true }).click()
  const result = await (await response).json()
  expect(result.result_type).toBe('answer')
  expect(result.intent).toBe('retail_query')
  expect(result.rows).toHaveLength(1)
  expect(result.answer.split(/\s+/).length).toBeLessThanOrEqual(20)
  await expect(page.getByLabel('Answer', { exact: true })).toContainText('is the most frequent issue')
  expect(await page.getByLabel('Answer', { exact: true }).evaluate(element => element === element.parentElement?.lastElementChild)).toBe(true)
  await page.getByText('View supporting results', { exact: true }).click()
  await expect(page.getByRole('list', { name: 'Query results' })).toContainText(result.rows[0].category)
  await expect(page.getByRole('table')).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Store', exact: true }).selectOption('ST004')
  await page.getByLabel('Analytics question').fill('Which products need replenishment?')
  await page.getByRole('button', { name: 'Ask', exact: true }).click()
  await expect(page.getByRole('list', { name: 'Query results' })).toContainText('On Hand')
  await expect(page.getByRole('list', { name: 'Query results' })).toContainText('ST004')
  await page.getByLabel('Analytics question').fill('What products are out of stock in ST004?')
  await page.getByRole('button', { name: 'Ask', exact: true }).click()
  await expect(page.getByLabel('Answer', { exact: true })).toContainText('No products are marked out of stock in ST004')
  await expect(page.getByRole('list', { name: 'Query results' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
})
